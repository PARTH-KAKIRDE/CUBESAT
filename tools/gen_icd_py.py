#!/usr/bin/env python3
"""Generate Python constants from the C ICD headers (the one source of truth).

    python tools/gen_icd_py.py          write obc/cubesat_obc/icd_defs.py
    python tools/gen_icd_py.py --check  exit 1 if the generated file is stale

Only lines of the form  #define NAME <integer>  are taken (see header rules).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADERS = [ROOT / "icd" / "cubesat_icd.h", ROOT / "icd" / "ground_link.h"]
OUT = ROOT / "obc" / "cubesat_obc" / "icd_defs.py"

DEFINE = re.compile(r"^\s*#define\s+([A-Z][A-Z0-9_]*)\s+\(?\s*(0[xX][0-9A-Fa-f]+|\d+)[uU]?\s*\)?\s*(?:/\*.*)?$")
GUARD = re.compile(r"^\s*#define\s+[A-Za-z_][A-Za-z0-9_]*\s*$")  # include guard: no value


def parse(path):
    out = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        m = DEFINE.match(line)
        if m:
            out.append((m.group(1), m.group(2)))
        elif line.lstrip().startswith("#define") and not GUARD.match(line):
            # Never drop a constant silently: Python would only fail later, at run time.
            raise SystemExit(f"{path.name}:{n}: cannot parse (use '#define NAME <integer>' "
                             f"with an optional /* comment */):\n    {line.strip()}")
    return out


def render():
    lines = [
        '"""GENERATED by tools/gen_icd_py.py from icd/*.h - DO NOT EDIT.',
        "",
        "Edit the C headers and re-run the generator instead.",
        '"""',
        "",
    ]
    seen = {}
    for h in HEADERS:
        lines.append(f"# --- {h.name} ---")
        for name, val in parse(h):
            if name in seen:
                raise SystemExit(f"{name} defined twice ({seen[name]} and {h.name})")
            seen[name] = h.name
            lines.append(f"{name} = {val}")
        lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date: run python tools/gen_icd_py.py")
            sys.exit(1)
        print("icd_defs.py is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
